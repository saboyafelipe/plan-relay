#!/bin/sh
# Checks the plugin environment. Single source for the autopilot preflight, the check
# skill and the panel: consumers read --json, never the text.
#
# Usage: sh check.sh [--json]
#   no arguments  one line per check and, at the end, what is missing and how to fix it
#   --json        a JSON object (shape below)
# Exit code: 0 when nothing required is missing (ok), 1 when something is, 2 on wrong usage.
#
# Shape of --json (part of the contract):
#   {"ok": <bool>, "checks": [{"id": <string>, "status": <status>,
#                              "required": <bool>, "detail": <string>}, …]}
#   ok        true when no check with required=true has status ≠ "ok"
#   status    "ok" · "missing" (not there) · "warning" (there, with a caveat)
#             · "unknown" (no way to tell here; never an error)
#   detail    text for people; on missing/warning it says how to fix it
#   The order of the checks is stable; new ids may appear, and consumers
#   ignore the ones they do not know.
#
# General checks: jq (required), git, os, shell.
# Agent checks: the agent adapter puts a check-agent.sh next to this script
# (the build copies it to the same folder), sourced with "." after the general
# ones. It defines check_agent(), which calls add with its own ids (agent-cli, agent-auth,
# plugin, plugin-current…). Without that file only the general checks run.
#
# The script does not depend on what it checks: it only uses sh, uname, sed and awk. It builds
# the JSON without jq. It does not touch the network nor read $HOME (the agent CLI may).
# Language: the package one, which the build writes below; the detail changes language, the ids
# and the --json keys do not.

language='{{PACKAGE_LANGUAGE}}'
# >>> strings (area check.): generated by tools/script-strings.sh from core/i18n/*.json; do not edit by hand
case "$language" in
  [Xx]-[Tt][Ee][Ss][Tt]) msg_language="x-test" ;;
  [Pp][Tt]-[Bb][Rr]) msg_language="pt-BR" ;;
  [Pp][Tt]|[Pp][Tt]-*) msg_language="pt-BR" ;;
  *) msg_language="en" ;;
esac
# shellcheck disable=SC2016,SC2089 # backticks and quotes in the strings are text, not expansion
case "$msg_language" in
  x-test) MSG_TABLE='check.usage	x-test:check.usage
check.required	x-test:check.required
check.optional	x-test:check.optional
check.jqMissing	x-test:check.jqMissing
check.gitMissing	x-test:check.gitMissing
check.unameMudo	x-test:check.unameMudo
check.shellGitBash	x-test:check.shellGitBash
check.shellCygwin	x-test:check.shellCygwin
check.shellPosix	x-test:check.shellPosix {0}
check.systemUnknown	x-test:check.systemUnknown
check.systemUnrecognized	x-test:check.systemUnrecognized {0}
check.missing	x-test:check.missing
check.allGood	x-test:check.allGood
' ;;
  pt-BR) MSG_TABLE='check.usage	Uso: sh check.sh [--json]
check.required	obrigatório
check.optional	opcional
check.jqMissing	jq não encontrado; o selftest.sh, o summary.sh e a janela de 5 h precisam dele. Instale: brew install jq (macOS) · sudo apt install jq (Debian/Ubuntu) · winget install jqlang.jq (Windows)
check.gitMissing	git não encontrado; sem ele não há commits do plano. Instale pelo gerenciador de pacotes do sistema ou em git-scm.com
check.unameMudo	uname não respondeu
check.shellGitBash	Git Bash (MSYS2) no Windows
check.shellCygwin	Cygwin no Windows
check.shellPosix	sh POSIX em {0}
check.systemUnknown	sistema desconhecido
check.systemUnrecognized	sistema não reconhecido ({0}); os scripts só estão provados em macOS e Linux. No Windows, use o Git Bash ou o WSL
check.missing	O que falta ou pede atenção:
check.allGood	Tudo em dia.
' ;;
  *) MSG_TABLE='check.usage	Usage: sh check.sh [--json]
check.required	required
check.optional	optional
check.jqMissing	jq not found; selftest.sh, summary.sh and the 5-hour window need it. Install: brew install jq (macOS) · sudo apt install jq (Debian/Ubuntu) · winget install jqlang.jq (Windows)
check.gitMissing	git not found; without it there are no plan commits. Install it with the system package manager or from git-scm.com
check.unameMudo	uname did not answer
check.shellGitBash	Git Bash (MSYS2) on Windows
check.shellCygwin	Cygwin on Windows
check.shellPosix	POSIX sh at {0}
check.systemUnknown	unknown system
check.systemUnrecognized	unrecognized system ({0}); the scripts are only proven on macOS and Linux. On Windows, use Git Bash or WSL
check.missing	What is missing or needs attention:
check.allGood	All good.
' ;;
esac
# shellcheck disable=SC2090 # a table read by awk from the environment, never split by the shell
export MSG_TABLE
MSG_AWK='
function msg_load(   m, ls, j, p) {
  msg_ok = 1
  m = split(ENVIRON["MSG_TABLE"], ls, "\n")
  for (j = 1; j <= m; j++) { p = index(ls[j], "\t"); if (p > 0) MSG[substr(ls[j], 1, p - 1)] = substr(ls[j], p + 1) }
}
function msg(k, a0, a1, a2, a3, a4, a5,   s, r, i, c) {
  if (!msg_ok) msg_load()
  s = (k in MSG) ? MSG[k] : k
  r = ""
  while ((i = index(s, "{")) > 0) {
    c = substr(s, i + 1, 2)
    if (c ~ /^[0-5][}]$/) {
      c = substr(c, 1, 1)
      r = r substr(s, 1, i - 1) (c == "0" ? a0 : (c == "1" ? a1 : (c == "2" ? a2 : (c == "3" ? a3 : (c == "4" ? a4 : a5)))))
      s = substr(s, i + 3)
    } else { r = r substr(s, 1, i); s = substr(s, i + 1) }
  }
  return r s
}
'
msg() { awk "$MSG_AWK"' BEGIN { print msg(ARGV[1], ARGV[2], ARGV[3], ARGV[4], ARGV[5], ARGV[6], ARGV[7]); exit }' "$@"; }
# <<< strings

json=
case "${1-}" in
  --json) json=1 ;;
  "") ;;
  *) msg check.usage >&2; exit 2 ;;
esac
[ $# -le 1 ] || { msg check.usage >&2; exit 2; }

case "$0" in */*) here=${0%/*} ;; *) here=. ;; esac

ok=true
role_required=$(msg check.required)
role_optional=$(msg check.optional)
json_out=
text_out=
missing_list=

# js <text>: quoted JSON string; control characters are dropped
js() { printf '"%s"' "$(printf '%s' "$1" | sed 's/[[:cntrl:]]//g; s/\\/\\\\/g; s/"/\\"/g')"; }

# add <id> <status> <required> <detail>
add() {
  if [ "$3" = true ] && [ "$2" != ok ]; then ok=false; fi
  item="{\"id\": $(js "$1"), \"status\": \"$2\", \"required\": $3, \"detail\": $(js "$4")}"
  if [ -z "$json_out" ]; then json_out="  $item"; else json_out="$json_out,
  $item"; fi
  if [ "$3" = true ]; then role=$role_required; else role=$role_optional; fi
  case "$2" in
    ok|unknown) line=$(printf '  %-8s %-15s %-13s %s' "$2" "$1" "$role" "$4") ;;
    *) line=$(printf '  %-8s %-15s %s' "$2" "$1" "$role")
       missing_list="$missing_list
  $1: $4" ;;
  esac
  text_out="$text_out$line
"
}

# --- general --------------------------------------------------------------

if p=$(command -v jq); then add jq ok true "$p"
else add jq missing true "$(msg check.jqMissing)"
fi
# shellcheck disable=SC2034 # read by the adapter's check-agent.sh
jq_path=$p

if p=$(command -v git); then add git ok false "$p"
else add git missing false "$(msg check.gitMissing)"
fi

sys=$(uname -s 2>/dev/null) || sys=
case "$sys" in
  Linux)
    case "$(uname -r 2>/dev/null)" in
      *[Mm]icrosoft*) add os ok false "Linux (WSL)" ;;
      *) add os ok false "Linux" ;;
    esac ;;
  "") add os unknown false "$(msg check.unameMudo)" ;;
  *) add os ok false "$sys" ;;
esac

case "$sys" in
  MINGW*|MSYS*) add shell ok false "$(msg check.shellGitBash)" ;;
  CYGWIN*) add shell ok false "$(msg check.shellCygwin)" ;;
  Linux|Darwin|*BSD|DragonFly|SunOS) add shell ok false "$(msg check.shellPosix "$(command -v sh)")" ;;
  "") add shell unknown false "$(msg check.systemUnknown)" ;;
  *) add shell warning false "$(msg check.systemUnrecognized "$sys")" ;;
esac

# --- agent ----------------------------------------------------------------

if [ -f "$here/check-agent.sh" ]; then
  # shellcheck source=/dev/null # comes from the agent adapter, next to this script in the package
  . "$here/check-agent.sh"
  check_agent
fi

# --- output ---------------------------------------------------------------

if [ -n "$json" ]; then
  printf '{"ok": %s, "checks": [\n%s\n]}\n' "$ok" "$json_out"
else
  printf '%s' "$text_out"
  if [ -n "$missing_list" ]; then printf '\n%s%s\n' "$(msg check.missing)" "$missing_list"
  else printf '\n%s\n' "$(msg check.allGood)"
  fi
fi
[ "$ok" = true ]
