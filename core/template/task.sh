# rollback <file whose rename failed>: each file already replaced goes back to the text it had, through a
# temporary and a rename; the temporaries that are left go away and the verb exits 1. If a restore fails
# too, the exit names the state each file was left in: replaced, restored or untouched.
rollback() {
  stuck=0
  report=""
  n=0
  while IFS=' ' read -r t a; do
    [ -n "$a" ] || continue
    n=$((n + 1))
    if [ "$n" -gt "$changed" ]; then
      line=$(msg task.stateUntouched "$a")
    elif [ -z "${TASK_TEST_FAIL_RESTORE:-}" ] && cp "$a.orig$suffix" "$a$suffix" 2>/dev/null && mv "$a$suffix" "$a" 2>/dev/null; then
      line=$(msg task.stateRestored "$a")
    else
      stuck=1
      line=$(msg task.stateReplaced "$a")
    fi
    report="$report  $line
"
  done < "$list"
  rm -f "$list" phase-*/*"$suffix"
  if [ "$stuck" = 0 ]; then
    msg task.rewriteFailed "$1" >&2
  else
    msg task.rewriteStuck "$1" >&2
    printf '%s' "$report" >&2
  fi
  exit 1
}

# Which locks (contract, "Lock"): claim, close, release and cancel change only the task. giveup --yes
# and reopen compute, without locks, the tasks they would change, take all those locks in plan order
# (one global order, so two writers never wait on each other in a cycle) and compute again under them.
# A dry run that refuses still takes the task's lock, so the refusal is given under it. A giveup
# preview writes nothing and takes none.
case "$action" in
  giveup|reopen)
    if [ "$action" = reopen ] || [ "$yes" = 1 ]; then
      ids=$(edit_plan dry 2>/dev/null) || ids=""
      for t in ${ids:-$id}; do take "$t"; done
    fi ;;
  *) take "$id" ;;
esac
state=$(header "$f" state)

case "$action" in
  claim)
    if [ "$state" = "in-progress" ]; then
      msg task.alreadyInProgress "$id" "$(header "$f" started)" >&2
      exit 1
    fi
    if [ "$state" != "ready" ]; then
      msg task.claimOnlyReady "$id" "$state" >&2
      exit 1
    fi
    blockers=$(header "$f" blockers)
    pending=""
    old_ifs=$IFS; IFS=,
    for b in $blockers; do
      [ -n "$b" ] || continue
      bf=$(task_file "$b")
      # no file, or more than one (a duplicated id, which has no state), is not done
      case "$bf" in ''|*"
"*) pending="$pending $b"; continue ;; esac
      if [ "$(header "$bf" state)" != "done" ]; then pending="$pending $b"; fi
    done
    IFS=$old_ifs
    if [ -n "$pending" ]; then
      msg task.stillWaiting "$id" "$pending" >&2
      exit 1
    fi
    rewrite "in-progress" "Started: $now"
    msg task.claimDone "$id" "$now"
    ;;
  close)
    if [ "$state" != "in-progress" ]; then
      msg task.closeOnlyInProgress "$id" "$state" >&2
      exit 1
    fi
    unchecked=$(awk '/^## Done when/ { c = 1; next } /^## / { c = 0 } c && /^- \[ \]/' "$f")
    if [ -n "$unchecked" ]; then
      msg task.doneWhenUnchecked "$id" >&2
      echo "$unchecked" >&2
      exit 1
    fi
    started=$(header "$f" started)
    if [ -n "$started" ]; then rewrite "done" "Started: $started\nFinished: $now"; else rewrite "done" "Finished: $now"; fi
    msg task.closeDone "$id" "$now"
    ;;
  release)
    if [ "$state" != "in-progress" ]; then
      msg task.releaseOnlyInProgress "$id" "$state" >&2
      exit 1
    fi
    rewrite "ready" ""
    msg task.releaseDone "$id"
    ;;
  cancel)
    edit_plan
    msg task.cancelDone "$id"
    ;;
  giveup)
    edit_plan
    [ "$yes" = 1 ] && msg task.giveupDone "$id" "$changed"
    ;;
  reopen)
    edit_plan
    msg task.reopenDone "$id" "$changed"
    ;;
esac
exit 0
