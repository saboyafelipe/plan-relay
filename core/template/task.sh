# The task files in plan order, one per line: phases by the N of phase-N-<slug> (phase-2 before
# phase-10) and, within a phase, by the value of each part of the id, as status.sh orders them.
# A name may hold spaces (contract), never a line break.
plan_files() {
  # shellcheck disable=SC2012 # ls -1 gives one name per line, and awk keeps each line whole
  ls -1 phase-*/F[0-9]*.md 2>/dev/null | awk -F/ '{
    f = $1; sub(/^phase-/, "", f); split(f, p, "-"); k = sprintf("%09d", p[1])
