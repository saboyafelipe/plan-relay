  # A rename that fails puts back the files already replaced (rollback). TASK_TEST_FAIL_RENAME=<n> makes the
  # n-th rename fail and TASK_TEST_FAIL_RESTORE=1 makes every restore fail, so the tests reach those paths.
  changed=0
  while IFS=' ' read -r t a; do
    [ -n "$a" ] || continue
    still_mine "$t" ""
    if [ "${TASK_TEST_FAIL_RENAME:-}" != "$((changed + 1))" ] && cp "$a" "$a.orig$suffix" 2>/dev/null && mv "$a$suffix" "$a" 2>/dev/null; then
