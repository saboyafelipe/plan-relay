    printf "%s\t%s\n", k, $0
  }' | sort | cut -f2
}

# A task is found by its whole id, in the form of the contract (F<n>-<nn> with optional .<k> parts),
# as the id at the start of the file name (the same reading as status.sh): a prefix or the id followed
# by the slug is not an id, and the lock is named after the id, so it is one per file.
task_file() { # $1 id; prints the files whose id it is, in plan order (more than one: a duplicated id), or nothing
  case "$1" in
    F[0-9]*-[0-9]*) ;;
    *) return 0 ;;
  esac
  if [ -n "$(printf '%s\n' "$1" | sed -n '/^F[0-9][0-9]*-[0-9][0-9]*\(\.[0-9][0-9]*\)*$/p')" ]; then
    plan_files | awk -v id="$1" '{ n = split($0, p, "/")
      if (match(p[n], /^F[0-9]+-[0-9]+(\.[0-9]+)*/) && substr(p[n], RSTART, RLENGTH) == id) print }'
  fi
  return 0
}
