# Locks (contract, "Writers"). A writer takes the lock of each task it changes, the directory
# .lock-<ID>: mkdir is atomic, so two sessions touching the same task pass one at a time, and the
# second already reads what the first one wrote. Right after mkdir the owner writes .lock-<ID>/owner,
# "<host> <pid> <UTC time>"; a lock without owner is being taken and counts as held. The trap releases
# the locks this process still owns (owner first, then the directory) on exit, on error and on
# HUP/INT/TERM, and removes the temporary files of a write that did not finish. A waiter gives up
# after TASK_LOCK_WAIT seconds (default 10) and refuses.
suffix=".tmp.$$"
held=""
me=""
host=$(uname -n 2>/dev/null)
stale_min=${TASK_LOCK_STALE_MIN:-1}
trap 'rm -f phase-*/*"$suffix" ".list$suffix" .lock-*/owner"$suffix"; release_locks' EXIT
trap 'exit 1' HUP INT TERM

# owner_of <id>: the owner line of the lock, or nothing
owner_of() { line=""; if [ -f ".lock-$1/owner" ]; then IFS= read -r line < ".lock-$1/owner"; fi; printf '%s' "$line"; }
# mine <id>: 0 when the lock still names this process
mine() { [ -n "$me" ] && [ "$(owner_of "$1")" = "$me" ]; }
# shellcheck disable=SC2329 # called from the EXIT trap string, which shellcheck does not follow
release_locks() {
  for x in $held; do
    if mine "$x"; then rm -f ".lock-$x/owner"; rmdir ".lock-$x" 2>/dev/null; fi
  done
}
# older <UTC time>: exit 0 when the time is more than stale_min minutes ago, 1 when not, 2 when it is
# not a time in the owner's form. Days from the civil date, so no date(1) extension is needed.
older() {
  awk -v t="$1" -v n="$(date -u +%Y-%m-%dT%H:%M:%SZ)" -v m="$stale_min" '
  function secs(x,   y, mo, d) {
    if (x !~ /^[0-9][0-9][0-9][0-9]-[0-9][0-9]-[0-9][0-9]T[0-9][0-9]:[0-9][0-9]:[0-9][0-9]Z$/) return -1
    y = substr(x, 1, 4) + 0; mo = substr(x, 6, 2) + 0; d = substr(x, 9, 2) + 0
    if (mo <= 2) { y--; mo += 12 }
    d = 365 * y + int(y / 4) - int(y / 100) + int(y / 400) + int((153 * (mo - 3) + 2) / 5) + d
    return d * 86400 + substr(x, 12, 2) * 3600 + substr(x, 15, 2) * 60 + substr(x, 18, 2)
  }
  BEGIN { a = secs(t); b = secs(n); if (a < 0 || b < 0) exit 2; exit (b - a > m * 60) ? 0 : 1 }'
}
alive() { kill -0 "$1" 2>/dev/null || ps -p "$1" >/dev/null 2>&1; }
# old_dir <dir>: 0 when its modification time is more than stale_min minutes ago
old_dir() { [ -n "$(find "$1" -prune -mmin +"$stale_min" 2>/dev/null)" ]; }
# is_orphan <id>: the owner names this machine and a process that is not running, or the lock is older
# than stale_min by the owner's time (by the directory's time without owner). Keeps the owner it judged in $judged.
is_orphan() {
  judged=$(owner_of "$1")
  if [ -n "$judged" ]; then
    # shellcheck disable=SC2086 # the owner line is split on purpose: host, pid, time
    set -- "$1" $judged
    case "$3" in ''|*[!0-9]*) ;; *) if [ "$2" = "$host" ] && ! alive "$3"; then return 0; fi ;; esac
    older "$4"
    case $? in 0) return 0 ;; 1) return 1 ;; esac
  fi
  old_dir ".lock-$1"
}
# steal <id>: renames the orphan away (one waiter wins the rename), checks it is the lock that was
# judged and removes it. A renamed lock that is not the judged one goes back when its name is free.
steal() {
  st=".lock-$1.stale.$$"
  rm -rf "$st"
  mv ".lock-$1" "$st" 2>/dev/null || return 1
  got=""
  if [ -f "$st/owner" ]; then IFS= read -r got < "$st/owner"; fi
  if [ "$got" != "$judged" ] || { [ -z "$got" ] && ! old_dir "$st"; }; then
    if [ ! -e ".lock-$1" ]; then mv "$st" ".lock-$1" 2>/dev/null; fi
    rm -rf "$st"
    return 1
  fi
  rm -rf "$st"
}
# take <id>: waits for the lock and takes it, or refuses with task.lockBusy
take() {
  [ -n "$me" ] || me="$host $$ $(date -u +%Y-%m-%dT%H:%M:%SZ)"
  tries=$((${TASK_LOCK_WAIT:-10} * 10))
  turn=0
  while :; do
    if mkdir ".lock-$1" 2>/dev/null; then
      held="$held $1"
      printf '%s\n' "$me" > ".lock-$1/owner$suffix" 2>/dev/null && mv ".lock-$1/owner$suffix" ".lock-$1/owner" 2>/dev/null && mine "$1" && return 0
      break
    fi
    # the orphan check runs on the first failure and then once a second, so a waiter does not spend a find on every turn
    if [ $((turn % 10)) -eq 0 ] && is_orphan "$1" && steal "$1"; then continue; fi
    turn=$((turn + 1))
    tries=$((tries - 1))
    [ "$tries" -gt 0 ] || break
    sleep 0.1 2>/dev/null || sleep 1
  done
  msg task.lockBusy "$1" "$cmd_path" ".lock-$1" >&2
  exit 1
}

# header <file> <name>: the value that the header reader keeps (state, started, blockers…; see HEADER_AWK).
header() { awk -v name="$2" "$HEADER_AWK"'FNR == 1 { id = hdr_begin() } !hdr_line(id) { exit } END { print hdr_get(id, name) }' "$1"; }

# TASK_TEST_NOW fixes the clock for the contract edit cases; unset, it is the current time.
now=${TASK_TEST_NOW:-$(date -u +%Y-%m-%dT%H:%MZ)}

# Before each rename the writer checks that the task's lock still names it: a lock that ran past
# TASK_LOCK_STALE_MIN may have been taken as an orphan. If not, it stops and writes nothing more.
still_mine() { # $1 id, $2 temporary to remove when the lock is no longer ours
  mine "$1" && return 0
  rm -f "$2" phase-*/*"$suffix"
  msg task.lockBusy "$1" "$cmd_path" ".lock-$1" >&2
  exit 1
}

# claim, close and release: the Status: line becomes the new one, every Started: and Finished: header line
# goes away, and the given lines go right after Status: (contract, "Writers"). Several lines to insert
# are separated by a literal \n (awk -v converts it).
rewrite() { # $1 status, $2 lines to insert (or empty)
  tmp="$f$suffix"
  awk -v st="$1" -v ins="$2" -v tmp="$tmp" "$HEADER_AWK"'BEGIN { hdr_write(ARGV[1], tmp, st, ins, "^(Started|Finished):", "") }' "$f" &&
    still_mine "$id" "$tmp" && mv "$tmp" "$f" && return 0
  rm -f "$tmp"
  msg task.rewriteFailed "$f" >&2
  exit 1
}

# cancel, giveup and reopen: one awk program reads the headers of every task, checks everything and,
# only if nothing refuses, writes each changing file to a temporary next to it (<file>.tmp.<pid>) and
# puts the path in a list; sh renames the temporaries at the end. So a refusal, or a write that fails
# midway, leaves the plan as it was. awk exits 0 (go on), 1 (refused, the reason on stderr) or any
# other code (the write failed). The reason and the options go through the environment, because
# awk's -v would interpret backslashes.
edit_plan() { # $1 "dry": only prints the ids that would change, in plan order, and writes nothing
  files=$(plan_files)
  list=".list$suffix"
  : > "$list" || { msg task.rewriteFailed "$f" >&2; exit 1; }
  # Split only on line breaks and without globbing, so a space or a [ in a name stays in it.
  old_ifs=$IFS
  IFS='
'
  set -f
  # shellcheck disable=SC2086 # $files is split on purpose: one argument per task
  PR_ACTION=$action PR_ID=$id PR_REASON=$reason PR_REPL=$repl PR_HAS_REPL=$has_repl PR_YES=$yes \
  PR_JSON=$as_json PR_PATH=$cmd_path PR_SUFFIX=$suffix PR_LIST=$list PR_DRY=${1:-} PR_LOCKED=$held awk "$MSG_AWK$HEADER_AWK"'
BEGIN {
  action = ENVIRON["PR_ACTION"]; root = ENVIRON["PR_ID"]; suffix = ENVIRON["PR_SUFFIX"]; list = ENVIRON["PR_LIST"]
  # In an awk that counts characters (UTF-8), a character already is a code point; in one that counts
  # bytes, the code point length comes from the first byte.
  UTF = (length("\303\251") == 1)
  for (i = 1; i < 256; i++) ORD[sprintf("%c", i)] = i
  for (i = 1; i < 32; i++) esc[sprintf("%c", i)] = sprintf("\\u%04x", i)
  esc["\t"] = "\\t"; esc["\n"] = "\\n"; esc["\r"] = "\\r"; esc["\\"] = "\\\\"; esc["\""] = "\\\""
}
# t is the key of the file (see HEADER_AWK): the id, or "<ID>#<n>" for a second file with the same id.
FNR == 1 {
  t = hdr_begin()
  order[++total] = t; file[t] = FILENAME; phase[t] = hdr_phase; exists[t] = 1
  if (!(hdr_phase in fseen)) { fseen[hdr_phase] = 1; phases[++nphases] = hdr_phase }
}
hdr_line(t) { next }
function refuse(s) { printf "%s\n", s | "cat 1>&2"; close("cat 1>&2"); failed = 1; exit 1 }
function is_dead(x) { return state[x] == "cancelled" || state[x] == "abandoned" }
function js(s,   r, i, c) {
  r = ""
  for (i = 1; i <= length(s); i++) { c = substr(s, i, 1); r = r ((c in esc) ? esc[c] : c) }
  return "\"" r "\""
}
function jsnull(s) { return s == "" ? "null" : js(s) }
# Refuses when the key belongs to a duplicated id: the id and its files, in plan order.
function refuse_dup(x,   d, i, r) {
  d = hdr_idof(x)
  if (!(d in hdr_dup)) return
  r = ""
  for (i = 1; i <= total; i++) if (hdr_idof(order[i]) == d) r = r (r == "" ? "" : ", ") file[order[i]]
  refuse(msg("task.ambiguousId", d, r))
}
# The reason: space, tab, LF and CR at the ends go away and each run inside becomes one space.
function normalize(s) { gsub(/[ \t\n\r]+/, " ", s); sub(/^ /, "", s); sub(/ $/, "", s); return s }
# 1 when the word is a single code point, alone or repeated.
function single_cp(w,   k, b, u, i) {
  k = 1
  if (!UTF) { b = ORD[substr(w, 1, 1)]; k = b >= 240 ? 4 : (b >= 224 ? 3 : (b >= 192 ? 2 : 1)) }
  if (length(w) % k) return 0
  u = substr(w, 1, k)
  for (i = 1; i <= length(w); i += k) if (substr(w, i, k) != u) return 0
  return 1
}
function valid_reason(s,   m, ws, j) {
  if (s == "") return 0
  m = split(s, ws, " ")
  for (j = 1; j <= m; j++) if (!single_cp(ws[j])) return 1
  return 0
}
# Queues a file for writing: new Status, the lines of the verb (separated by "\n") and the ## Log line.
function queue(x, st, ins, line) { nm++; m_id[nm] = x; m_est[nm] = st; m_ins[nm] = ins; m_log[nm] = line }
# Writes the temporary of a file by the contract, "What the verbs write".
function write_tmp(k,   fname) {
  fname = file[m_id[k]]
  printf "%s %s\n", m_id[k], fname > list
  hdr_write(fname, fname suffix, m_est[k], m_ins[k], "^(Replaced by|Given up by|Given up with|Previous status):", m_log[k])
}
# giveup: the closure of the dependents breadth-first (queue), the parent being the first that reaches it.
function closure(   h, x, m, ds, j, d) {
  q[1] = root; nq = 1; falls[root] = 1; depth[root] = 0; parent[root] = ""
  for (h = 1; h <= nq; h++) {
    x = q[h]
    m = split(deps[x], ds, " ")
    for (j = 1; j <= m; j++) {
      d = ds[j]
      if (d == "" || (d in falls) || is_dead(d)) continue
      falls[d] = 1; parent[d] = x; depth[d] = depth[x] + 1; q[++nq] = d
    }
  }
}
# The tree in pre-order: the root, then each child followed by its subtree, children in plan order.
function preorder(x,   i, y) {
  tree[++na] = x
  for (i = 1; i <= total; i++) { y = order[i]; if ((y in falls) && y != root && parent[y] == x) preorder(y) }
}
function also_on(x,   m, bs, j, b, r) {
  r = ""
  if (x == root) return r
  m = split(blockers[x], bs, ",")
  for (j = 1; j <= m; j++) {
    b = bs[j]
    if (b == "" || !(b in exists) || (b in falls) || state[b] == "done" || is_dead(b)) continue
    r = r (r == "" ? "" : ",") b
  }
  return r
}
# Abandoned phase: every task in it cancelled or abandoned and at least one abandoned; with apply, counts those that fall.
function abandoned_phase(fs, apply,   i, x, e, ab) {
  ab = 0
  for (i = 1; i <= total; i++) {
    x = order[i]
    if (phase[x] != fs) continue
    e = (apply && (x in falls)) ? "abandoned" : state[x]
    if (e == "abandoned") ab = 1
    else if (e != "cancelled") return 0
  }
  return ab
}
# The END block runs one verb in four steps, each a function below: index_dependents, then the
# checks of the verb (do_cancel, do_giveup or do_reopen), which refuse (exit 1) or queue the files
# that change, then write_queue. Every check runs before the first write, so a refusal writes nothing.
# Plain POSIX awk functions, recursion included (preorder), as BSD awk, gawk, mawk and BusyBox take.
# No single quotes in this program: it is a single-quoted sh string.

# deps[<key>]: the keys whose Blocked by: cites it, in plan order, separated by spaces.
function index_dependents(   i, x, m, bs, j) {
  for (i = 1; i <= total; i++) {
    x = order[i]
    m = split(blockers[x], bs, ",")
    for (j = 1; j <= m; j++) if (bs[j] != "") deps[bs[j]] = deps[bs[j]] " " x
  }
}
# cancel guarantees, in this order: the root is live (draft, ready, in-progress); a replacement, when
# given, exists, is another task and is live; no live task cites the root (each such id named once);
# the reason is valid. Then it queues the root alone: cancel never cascades.
function do_cancel(e,   repl, alive, m, ds, j, d) {
  repl = ENVIRON["PR_REPL"]
  if (e != "draft" && e != "ready" && e != "in-progress") refuse(msg("task.cancelOnlyLive", root, e))
  if (ENVIRON["PR_HAS_REPL"] == "1" && (!(repl in exists) || repl == root || is_dead(repl))) refuse(msg("task.invalidReplacement", root, repl))
  alive = ""
  m = split(deps[root], ds, " ")
  for (j = 1; j <= m; j++) {
    d = ds[j]
    if (d == "" || is_dead(d) || (hdr_idof(d) in seen)) continue
    seen[hdr_idof(d)] = 1; alive = alive (alive == "" ? "" : ", ") hdr_idof(d)
  }
  if (alive != "") refuse(msg("task.cancelHasDependents", root, alive))
  if (!valid_reason(reason)) refuse(msg("task.invalidReason"))
  if (ENVIRON["PR_HAS_REPL"] == "1") queue(root, "cancelled", "Replaced by: " repl, msg("task.logCancelReplaced", repl, reason))
  else queue(root, "cancelled", "", msg("task.logCancel", reason))
}
# giveup guarantees, in this order: the root is ready or draft; no task that would fall has a
# duplicated id; every task that would fall is ready or draft (one that started or finished stops it
# all). It fills tree[1..na] (the root first, then pre-order) and phases_ab (the phases that become
# abandoned). Without --yes it prints the preview, JSON or text, and exits 0 having queued nothing;
# with --yes and a valid reason it queues every task of the tree.
function do_giveup(e,   k, x, stuck, i, prev) {
  if (e != "ready" && e != "draft") refuse(msg("task.giveupOnlyReadyOrDraft", root, e))
  closure()
  na = 0; preorder(root)
  for (k = 2; k <= na; k++) refuse_dup(tree[k])
  stuck = ""
  for (k = 2; k <= na; k++) {
    x = tree[k]
    if (state[x] != "ready" && state[x] != "draft") stuck = stuck (stuck == "" ? "" : ", ") x " (" state[x] ")"
  }
  if (stuck != "") refuse(msg("task.giveupStuck", root, stuck))
  phases_ab = ""
  for (i = 1; i <= nphases; i++) if (!abandoned_phase(phases[i], 0) && abandoned_phase(phases[i], 1)) phases_ab = phases_ab (phases_ab == "" ? "" : ",") phases[i]
  if (ENVIRON["PR_YES"] != "1" && ENVIRON["PR_JSON"] == "1") { preview_json(); exit 0 }
  if (ENVIRON["PR_YES"] != "1") { preview_text(); exit 0 }
  if (!valid_reason(reason)) refuse(msg("task.invalidReason"))
  for (k = 1; k <= na; k++) {
    x = tree[k]
    prev = state[x] == "draft" ? "\nPrevious status: draft" : ""
    if (x == root) queue(x, "abandoned", "Given up by: owner" prev, msg("task.logGiveup", reason))
    else queue(x, "abandoned", "Given up with: " root prev, msg("task.logGiveupWith", root))
  }
}
# The giveup preview as the contract object: root, falls (in tree order) and abandoned_phases.
function preview_json(   k, x, mt, ts, r, j, mf, fs) {
  printf "{\"root\": %s,\n \"falls\": [", js(root)
  for (k = 1; k <= na; k++) {
    x = tree[k]
    mt = split(also_on(x), ts, ",")
    r = ""; for (j = 1; j <= mt; j++) r = r (j > 1 ? ", " : "") js(ts[j])
    printf "%s\n   {\"id\": %s, \"title\": %s, \"status\": %s, \"phase\": %s, \"parent\": %s, \"depth\": %d, \"also_depends_on\": [%s]}", \
      (k > 1 ? "," : ""), js(x), js(title[x]), js(state[x]), js(phase[x]), jsnull(parent[x]), depth[x], r
  }
  mf = split(phases_ab, fs, ",")
  r = ""; for (j = 1; j <= mf; j++) r = r (j > 1 ? ", " : "") js(fs[j])
  printf "\n ],\n \"abandoned_phases\": [%s]}\n", r
}
# The giveup preview for people: the tree indented by depth, the phases that become abandoned and the
# command that applies it.
function preview_text(   k, x, indent, j, tb, pa) {
  print msg("task.giveupPreview", root, na)
  for (k = 1; k <= na; k++) {
    x = tree[k]; indent = ""
    for (j = 0; j <= depth[x]; j++) indent = indent "  "
    tb = also_on(x); gsub(/,/, ", ", tb)
    printf "%s%s  %s  [%s · %s]%s\n", indent, x, title[x], phase[x], state[x], (tb == "" ? "" : "  · " msg("task.giveupAlso", tb))
  }
  pa = phases_ab
  if (pa != "") { gsub(/,/, ", ", pa); print msg("task.giveupPhases", pa) }
  print msg("task.giveupNothingChanged", ENVIRON["PR_PATH"], root)
}
# 1 for the root of a reopen and for each task that fell with it.
function in_reopen(x) { return x == root || (state[x] == "abandoned" && fell_with[x] == root) }
# reopen guarantees, in this order: the root is abandoned; it is the root of its give-up, not a task
# that fell with another; no task of the group has a duplicated id. Then it queues the group, each
# back to its previous state (draft when Previous status: says so, ready otherwise).
function do_reopen(e,   i, x, back) {
  if (e != "abandoned") refuse(msg("task.reopenOnlyAbandoned", root, e))
  if (fell_with[root] != "") refuse(msg("task.reopenAtRoot", root, fell_with[root]))
  for (i = 1; i <= total; i++) if (in_reopen(order[i])) refuse_dup(order[i])
  for (i = 1; i <= total; i++) {
    x = order[i]
    if (!in_reopen(x)) continue
    back = prev_state[x] == "draft" ? "draft" : "ready"
    if (x == root) queue(x, back, "", msg("task.logReopen"))
    else queue(x, back, "", msg("task.logReopenWith", root))
  }
}
# The files that change, in plan order: the dry run prints their ids; the real one refuses if a
# lock it does not hold is needed (the set grew since the dry run) and then writes them.
function write_queue(   k, qk, i, locked) {
  for (k = 1; k <= nm; k++) qk[m_id[k]] = k
  if (ENVIRON["PR_DRY"] == "dry") { for (i = 1; i <= total; i++) if (order[i] in qk) print order[i]; exit 0 }
  locked = " " ENVIRON["PR_LOCKED"] " "
