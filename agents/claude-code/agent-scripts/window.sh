#!/bin/sh
# The 5-hour window of the Claude plan, so that the {{AGENT_PLUGIN_SKILL_PREFIX}}run conductor knows when to
# stop.
# Probe: a minimal headless call (Haiku, a short answer) whose stream brings the
# rate_limit_event with unifiedWindows.five_hour.
#   --read [threshold]  one line: five_hour=<%> reset=<epoch> age=<s> status=<state>
#                    (threshold 85 by default; the probe runs at most every 5 min, and
#                    between probes the cache is read). States:
#                      ok · stop (≥ threshold) · renewed (the stored reset has passed)
#                      no-data  the call failed (no claude, no network, error)
#                      timeout  the call did not answer within PLAN_RELAY_WINDOW_TIMEOUT
#                                 seconds (60 by default) and was killed
#                      unknown-format  the call answered, but without the
#                                 rate_limit_event with five_hour (the format, which
#                                 is not documented, changed), or the cache has a
#                                 utilization or resetsAt that is not a number
#                      off  the probe is opt-in and PLAN_RELAY_WINDOW is not on; nothing
#                                 is called or read
#                      no-subscription  ANTHROPIC_BASE_URL, ANTHROPIC_AUTH_TOKEN or
#                                 ANTHROPIC_API_KEY is in the environment: the session
#                                 does not pay through the subscription; nothing is
#                                 called or read
#                    Outside ok/stop/renewed the numeric fields come out as "?".
#   --wait           sleeps until the stored reset + 60 s and exits; run it in the
#                    background, the end of the process wakes the conductor. With off:
#                    exits at once, with 0; with a resetsAt that is not a number: exits 1.
# A threshold that is not only digits is wrong usage (exit 1).
# Cost: each probe is a real call to Haiku with a minimal context (~1k input tokens, 4 output
# ones), which counts in the subscription quota; with an API key there is no 5-hour window
# and the probe only spends. It is opt-in: turn it on with PLAN_RELAY_WINDOW=on (1, true and
# yes are also accepted); unset or any other value, it is off.
#   --data <dir>     state folder; else CLAUDE_PLUGIN_DATA, else the default folder
#                    ${XDG_STATE_HOME:-~/.local/state}/plan-relay/. The Bash calls of a
#                    skill do not inherit CLAUDE_PLUGIN_DATA, and a skill cites no variable
#                    in its body: the skill runs without --data, and its --read and --wait
#                    land in the same default folder.
# The cache is <data>/window.json.
# The --read line is a contract (keys and states in English); the rest comes out in the
# package language.

language='{{PACKAGE_LANGUAGE}}'
# >>> strings (area window.): generated by tools/script-strings.sh from agents/claude-code/i18n/*.json; do not edit by hand
case "$language" in
  [Xx]-[Tt][Ee][Ss][Tt]) msg_language="x-test" ;;
  [Pp][Tt]-[Bb][Rr]) msg_language="pt-BR" ;;
  [Pp][Tt]|[Pp][Tt]-*) msg_language="pt-BR" ;;
  *) msg_language="en" ;;
esac
# shellcheck disable=SC2016,SC2089 # backticks and quotes in the strings are text, not expansion
case "$msg_language" in
  x-test) MSG_TABLE='window.usage	x-test:window.usage
window.off	x-test:window.off
window.noSubscription	x-test:window.noSubscription
window.noReset	x-test:window.noReset
window.badReset	x-test:window.badReset
window.renewed	x-test:window.renewed {0}
' ;;
  pt-BR) MSG_TABLE='window.usage	Uso: sh window.sh --read [limiar] | --wait [--data <dir>]
window.off	sonda da janela de 5 h desligada (ligue com PLAN_RELAY_WINDOW=on): nada a esperar
window.noSubscription	sem assinatura (ANTHROPIC_BASE_URL, ANTHROPIC_AUTH_TOKEN ou ANTHROPIC_API_KEY): nada a esperar
window.noReset	sem resetsAt na cache: rodar --read primeiro
window.badReset	resetsAt da cache não é um número: nada a esperar
window.renewed	janela de 5 h reposta às {0}
' ;;
  *) MSG_TABLE='window.usage	Usage: sh window.sh --read [threshold] | --wait [--data <dir>]
window.off	5-hour window probe off (turn it on with PLAN_RELAY_WINDOW=on): nothing to wait for
window.noSubscription	no subscription (ANTHROPIC_BASE_URL, ANTHROPIC_AUTH_TOKEN or ANTHROPIC_API_KEY): nothing to wait for
window.noReset	no resetsAt in the cache: run --read first
window.badReset	resetsAt in the cache is not a number: nothing to wait for
window.renewed	5-hour window reset at {0}
' ;;
esac
# shellcheck disable=SC2090 # a table read by awk from the environment, never split by the shell
export MSG_TABLE
MSG_AWK='
function msg_load(   m, ls, j, p) {
  msg_ok = 1
  m = split(ENVIRON["MSG_TABLE"], ls, "\n")
  for (j = 1; j <= m; j++) { p = index(ls[j], "\t"); if (p > 0) MSG[substr(ls[j], 1, p - 1)] = substr(ls[j], p + 1) }
}
function msg(k, a0, a1, a2, a3, a4, a5,   s, r, i, c) {
  if (!msg_ok) msg_load()
  s = (k in MSG) ? MSG[k] : k
  r = ""
  while ((i = index(s, "{")) > 0) {
    c = substr(s, i + 1, 2)
    if (c ~ /^[0-5][}]$/) {
      c = substr(c, 1, 1)
      r = r substr(s, 1, i - 1) (c == "0" ? a0 : (c == "1" ? a1 : (c == "2" ? a2 : (c == "3" ? a3 : (c == "4" ? a4 : a5)))))
      s = substr(s, i + 3)
    } else { r = r substr(s, 1, i); s = substr(s, i + 1) }
  }
  return r s
}
'
msg() { awk "$MSG_AWK"' BEGIN { print msg(ARGV[1], ARGV[2], ARGV[3], ARGV[4], ARGV[5], ARGV[6], ARGV[7]); exit }' "$@"; }
# <<< strings

usage() { msg window.usage >&2; exit 1; }

action=; threshold=; data=
while [ $# -gt 0 ]; do
  case "$1" in
    --read|--wait) action=$1 ;;
    --data) [ $# -ge 2 ] || usage; data=$2; shift ;;
    *[!0-9]*) usage ;;
    [0-9]*) [ "$action" = --read ] || usage; threshold=$1 ;;
    *) usage ;;
  esac
  shift
done
[ -n "$action" ] || usage

case "${PLAN_RELAY_WINDOW-}" in
  on|ON|On|1|true|TRUE|True|yes|YES|Yes) ;;
  *)
    if [ "$action" = --read ]; then printf '%s\n' "five_hour=? reset=? age=? status=off"
    else msg window.off
    fi
    exit 0 ;;
esac

# No subscription: with one of these in the environment, the probe's claude -p does not use
# the claude.ai login, but their key or proxy (in the VS Code Agents window, Copilot's local
# proxy): the probe would spend another account's quota and bring no window. Only whether
# they are set is tested; the value is never read.
if [ -n "${ANTHROPIC_BASE_URL-}" ] || [ -n "${ANTHROPIC_AUTH_TOKEN-}" ] || [ -n "${ANTHROPIC_API_KEY-}" ]; then
  if [ "$action" = --read ]; then printf '%s\n' "five_hour=? reset=? age=? status=no-subscription"
  else msg window.noSubscription
  fi
  exit 0
fi

[ -n "$data" ] || data=${CLAUDE_PLUGIN_DATA:-${XDG_STATE_HOME:-$HOME/.local/state}/plan-relay}

cache="$data/window.json"
mkdir -p "$data" 2>/dev/null

# Modification time as an epoch. GNU first: on BSD `stat -c` fails cleanly, but on GNU
# `stat -f` is accepted and prints the file system status, which breaks the arithmetic.
if stat -c %Y / >/dev/null 2>&1; then mtime() { stat -c %Y "$1" 2>/dev/null || printf '0\n'; }
else mtime() { stat -f %m "$1" 2>/dev/null || printf '0\n'; }
fi
age() { printf '%s\n' $(( $(date +%s) - $(mtime "$cache") )); }

# probe: renews the cache when the event comes (even if claude exits with an error: that is
# the case of a used-up quota). Without the event, returns 2 if the call answered (unknown
# format) and 1 if it failed (no data).
probe() {
  tmp="$cache.tmp.$$"
  raw="$cache.raw.$$"
  # No tools, MCP, settings (hooks, plugins), skills or Claude Code system prompt: ~1k input
  # tokens, against ~40k for a plain claude -p (measured on 2026-11-14). Do not use --bare:
  # it does not read the subscription login.
  # Observed on Claude Code 2.1.316 (2026-11-15), not documented: the stream has the events
  # system/init, assistant, rate_limit_event and result/success. The rate_limit_event carries
  # rate_limit_info with isUsingOverage, overageDisabledReason, overageStatus,
  # rateLimitType, resetsAt, status and unifiedWindows; unifiedWindows has five_hour and
  # seven_day, and five_hour is {"utilization": 0.16, "resetsAt": <epoch, seconds>,
  # "status": "allowed"}. utilization is a fraction of 1.
  # The call runs in the background under a watchdog: it is killed after the timeout
  # (PLAN_RELAY_WINDOW_TIMEOUT seconds, 60 by default). exec makes the subshell's pid the
  # claude's, so the kill reaches it.
  limit=${PLAN_RELAY_WINDOW_TIMEOUT:-60}
  case $limit in ''|0*|*[!0-9]*) limit=60 ;; esac
  ( cd "${TMPDIR:-/tmp}" && exec claude -p --model haiku --max-turns 1 \
      --tools "" --strict-mcp-config --setting-sources "" --disable-slash-commands \
      --no-session-persistence --system-prompt "Reply with: ok" \
      --output-format stream-json --verbose "ok" ) > "$raw" 2>/dev/null < /dev/null &
  call=$!
  ( sleep "$limit"; : > "$raw.timeout"; kill "$call" ) >/dev/null 2>&1 &
  dog=$!
  { wait "$call"; } 2>/dev/null
  rc=$?
  kill "$dog" >/dev/null 2>&1
  wait "$dog" 2>/dev/null
  if [ -e "$raw.timeout" ]; then rm -f "$raw" "$raw.timeout"; return 3; fi
  grep '"type":"rate_limit_event"' "$raw" | tail -1 \
    | jq -c '.rate_limit_info.unifiedWindows.five_hour // empty | select(type == "object")' > "$tmp" 2>/dev/null
  if [ -s "$tmp" ]; then mv "$tmp" "$cache"; rm -f "$raw"; return 0; fi
  rm -f "$tmp"
  if [ "$rc" -eq 0 ] && [ -s "$raw" ]; then rm -f "$raw"; return 2; fi
  rm -f "$raw"; return 1
}

without() { printf '%s\n' "five_hour=? reset=? age=? status=$1"; exit 0; }

case "$action" in
  --read)
    threshold=${threshold:-85}
    if [ ! -s "$cache" ] || [ "$(age)" -ge 300 ]; then
      probe; r=$?
      [ "$r" -eq 2 ] && without unknown-format
      [ "$r" -eq 3 ] && without timeout
    fi
    [ -s "$cache" ] || without no-data
    pct=$(jq -r '(.utilization * 100) | floor' "$cache" 2>/dev/null)
    case "$pct" in ''|*[!0-9]*) without unknown-format ;; esac
    reset=$(jq -r '.resetsAt // empty' "$cache" 2>/dev/null)
    case "$reset" in *[!0-9]*) without unknown-format ;; esac
    now=$(date +%s)
    if [ -n "$reset" ] && [ "$now" -ge "$reset" ]; then state=renewed
    elif [ "$pct" -ge "$threshold" ]; then state=stop
    else state=ok
    fi
    printf '%s\n' "five_hour=$pct reset=${reset:-?} age=$(age)s status=$state"
    ;;
  --wait)
    reset=$(jq -r '.resetsAt // empty' "$cache" 2>/dev/null)
    if [ -z "$reset" ]; then msg window.noReset >&2; exit 1; fi
    case "$reset" in *[!0-9]*) msg window.badReset >&2; exit 1 ;; esac
    left=$((reset + 60 - $(date +%s)))
    [ "$left" -gt 21600 ] && left=21600
    [ "$left" -gt 0 ] && sleep "$left"
    rm -f "$cache"
    msg window.renewed "$(date '+%H:%M')"
    ;;
esac
